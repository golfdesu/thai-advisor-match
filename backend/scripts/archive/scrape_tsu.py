def seed_db():
    if not DB_AVAILABLE:
        logger.error("Database connection not available. Skipping DB commit.")
        return 0

    Base.metadata.create_all(bind=engine)
    session = SessionLocal()
    inserted = 0
    updated = 0
    try:
        for c in TSU_COURSES:
            existing = session.query(CourseDB).filter_by(id=c["id"]).first()
            if existing:
                for k, v in c.items():
                    setattr(existing, k, v)
                updated += 1
            else:
                session.add(CourseDB(**c))
                inserted += 1
        session.commit()
        logger.info(f"=== Successfully seeded Thaksin University: {inserted} inserted, {updated} updated ===")
        return inserted + updated
    except Exception as e:
        session.rollback()
        logger.error(f"Error seeding Thaksin University DB: {e}")
        return 0
    finally:
        session.close()

if __name__ == "__main__":
    count = seed_db()
    print(f"TSU courses processed: {count}")
